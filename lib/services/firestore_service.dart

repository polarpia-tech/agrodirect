import 'package:cloud_firestore/cloud_firestore.dart';
import '../models/crop_model.dart';

class FirestoreService {
  final FirebaseFirestore _db = FirebaseFirestore.instance;

  // Προσθήκη νέας καλλιέργειας
  Future<void> addCrop(CropModel crop) async {
    await _db.collection('crops').add(crop.toMap());
  }

  // Λήψη καλλιεργειών του συνδεδεμένου χρήστη (για το Τετράδιο Αγρότη)
  Stream<List<CropModel>> getUserCropsStream(String userId) {
    return _db
        .collection('crops')
        .where('userId', isEqualTo: userId)
        .snapshots()
        .map((snapshot) => snapshot.docs
            .map((doc) => CropModel.fromMap(doc.data(), doc.id))
            .toList());
  }

  // Λήψη μόνο των δημοσιευμένων καλλιεργειών (για την Αγορά)
  Stream<QuerySnapshot> getMarketplaceCropsStream() {
    return _db
        .collection('crops')
        .where('isPublished', isEqualTo: true)
        .snapshots();
  }

  // Αλλαγή κατάστασης δημοσίευσης (Δημοσίευση / Απόσυρση)
  Future<void> togglePublishCrop(String cropId, bool isPublished) async {
    await _db.collection('crops').doc(cropId).update({
      'isPublished': isPublished,
    });
  }
}
