import 'package:flutter/material.dart';
import 'add_crop_screen.dart';
import '../models/crop_model.dart';
import '../services/firestore_service.dart';

class CropsScreen extends StatefulWidget {
  const CropsScreen({Key? key}) : super(key: key);

  @override
  State<CropsScreen> createState() => _CropsScreenState();
}

class _CropsScreenState extends State<CropsScreen> {
  final FirestoreService _firestoreService = FirestoreService();

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text('Τετράδιο Αγρότη'),
        backgroundColor: Colors.green[800],
        foregroundColor: Colors.white,
      ),
      body: StreamBuilder<List<CropModel>>(
        stream: _firestoreService.getCropsStream(),
        builder: (context, snapshot) {
          // Αν φορτώνει
          if (snapshot.connectionState == ConnectionState.waiting) {
            return const Center(child: CircularProgressIndicator());
          }

          // Αν υπάρχει σφάλμα
          if (snapshot.hasError) {
            return Center(child: Text('Σφάλμα: ${snapshot.error}'));
          }

          // Αν η λίστα είναι άδεια
          if (!snapshot.hasData || snapshot.data!.isEmpty) {
            return const Center(
              child: Text(
                'Δεν υπάρχουν καλλιέργειες.\nΠροσθέστε την πρώτη σας!',
                textAlign: TextAlign.center,
                style: TextStyle(fontSize: 16),
              ),
            );
          }

          final crops = snapshot.data!;

          // Εμφάνιση λίστας
          return ListView.builder(
            itemCount: crops.length,
            itemBuilder: (context, index) {
              final crop = crops[index];
              return Card(
                margin: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
                elevation: 2,
                child: ListTile(
                  leading: const Icon(Icons.eco, color: Colors.green, size: 32),
                  title: Text(
                    crop.productName,
                    style: const TextStyle(fontWeight: FontWeight.bold),
                  ),
                  subtitle: Text(
                    '${crop.areaInAcre} στρέμματα • ${crop.estimatedQuantityTons} τόνοι\nΚατάσταση: ${crop.status}',
                  ),
                  isThreeLine: true,
                  onTap: () {
                    // Αργότερα εδώ θα πηγαίνουμε στην οθόνη Εξόδων της καλλιέργειας
                  },
                ),
              );
            },
          );
        },
      ),
      floatingActionButton: FloatingActionButton(
        backgroundColor: Colors.green[800],
        foregroundColor: Colors.white,
        child: const Icon(Icons.add),
        onPressed: () {
          Navigator.of(context).push(
            MaterialPageRoute(builder: (context) => const AddCropScreen()),
          );
        },
      ),
    );
  }
}
