import 'package:flutter/material.dart';
import 'package:cloud_firestore/cloud_firestore.dart';
import '../models/crop_model.dart';
import '../services/firestore_service.dart';

class CropDetailsScreen extends StatefulWidget {
  final CropModel crop;

  const CropDetailsScreen({Key? key, required this.crop}) : super(key: key);

  @override
  State<CropDetailsScreen> createState() => _CropDetailsScreenState();
}

class _CropDetailsScreenState extends State<CropDetailsScreen> {
  final FirestoreService _firestoreService = FirestoreService();
  late bool _isPublished;

  @override
  void initState() {
    super.initState();
    _isPublished = widget.crop.isPublished;
  }

  void _showAddExpenseDialog() {
    final titleController = TextEditingController();
    final amountController = TextEditingController();
    String selectedCategory = 'Καύσιμα';

    showDialog(
      context: context,
      builder: (context) => StatefulBuilder(
        builder: (context, setDialogState) => AlertDialog(
          title: const Text('Προσθήκη Εξόδου'),
          content: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              TextField(
                controller: titleController,
                decoration: const InputDecoration(labelText: 'Περιγραφή (π.χ. Πετρέλαιο)'),
              ),
              const SizedBox(height: 8),
              TextField(
                controller: amountController,
                keyboardType: TextInputType.number,
                decoration: const InputDecoration(labelText: 'Ποσό (€)'),
              ),
              const SizedBox(height: 12),
              DropdownButtonFormField<String>(
                value: selectedCategory,
                items: ['Καύσιμα', 'Λιπάσματα', 'Ημερομίσθια', 'Φάρμακα', 'Άλλα']
                    .map((cat) => DropdownMenuItem(value: cat, child: Text(cat)))
                    .toList(),
                onChanged: (val) {
                  if (val != null) setDialogState(() => selectedCategory = val);
                },
                decoration: const InputDecoration(labelText: 'Κατηγορία'),
              ),
            ],
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.of(context).pop(),
              child: const Text('Ακύρωση'),
            ),
            ElevatedButton(
              onPressed: () async {
                final title = titleController.text;
                final amount = double.tryParse(amountController.text) ?? 0.0;
                if (title.isNotEmpty && amount > 0 && widget.crop.id != null) {
                  await _firestoreService.addExpense(
                    cropId: widget.crop.id!,
                    title: title,
                    amount: amount,
                    category: selectedCategory,
                  );
                  if (mounted) Navigator.of(context).pop();
                }
              },
              child: const Text('Αποθήκευση'),
            ),
          ],
        ),
      ),
    );
  }

  void _showAddRevenueDialog() {
    final titleController = TextEditingController();
    final amountController = TextEditingController();

    showDialog(
      context: context,
      builder: (context) => AlertDialog(
        title: const Text('Προσθήκη Εσόδου / Πώλησης'),
        content: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            TextField(
              controller: titleController,
              decoration: const InputDecoration(labelText: 'Περιγραφή (π.χ. Πώληση σε έμπορο)'),
            ),
            const SizedBox(height: 8),
            TextField(
              controller: amountController,
              keyboardType: TextInputType.number,
              decoration: const InputDecoration(labelText: 'Ποσό (€)'),
            ),
          ],
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(context).pop(),
            child: const Text('Ακύρωση'),
          ),
          ElevatedButton(
            style: ElevatedButton.styleFrom(backgroundColor: Colors.green[800], foregroundColor: Colors.white),
            onPressed: () async {
              final title = titleController.text;
              final amount = double.tryParse(amountController.text) ?? 0.0;
              if (title.isNotEmpty && amount > 0 && widget.crop.id != null) {
                await _firestoreService.addRevenue(
                  cropId: widget.crop.id!,
                  title: title,
                  amount: amount,
                );
                if (mounted) Navigator.of(context).pop();
              }
            },
            child: const Text('Αποθήκευση'),
          ),
        ],
      ),
    );
  }

  void _showAddTaskDialog() {
    final titleController = TextEditingController();

    showDialog(
      context: context,
      builder: (context) => AlertDialog(
        title: const Text('Νέα Εργασία Χωραφιού'),
        content: TextField(
          controller: titleController,
          decoration: const InputDecoration(labelText: 'Εργασία (π.χ. Πότισμα, Ψεκασμός)'),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(context).pop(),
            child: const Text('Ακύρωση'),
          ),
          ElevatedButton(
            style: ElevatedButton.styleFrom(backgroundColor: Colors.green[800], foregroundColor: Colors.white),
            onPressed: () async {
              final title = titleController.text;
              if (title.isNotEmpty && widget.crop.id != null) {
                await _firestoreService.addTask(
                  cropId: widget.crop.id!,
                  title: title,
                );
                if (mounted) Navigator.of(context).pop();
              }
            },
            child: const Text('Προσθήκη'),
          ),
        ],
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    if (widget.crop.id == null) {
      return Scaffold(
        appBar: AppBar(title: Text(widget.crop.productName)),
        body: const Center(child: Text('Σφάλμα: Δεν βρέθηκε αναγνωριστικό καλλιέργειας.')),
      );
    }

    return Scaffold(
      appBar: AppBar(
        title: Text(widget.crop.productName),
        backgroundColor: Colors.green[800],
        foregroundColor: Colors.white,
      ),
      body: StreamBuilder<DocumentSnapshot>(
        stream: FirebaseFirestore.instance.collection('crops').doc(widget.crop.id).snapshots(),
        builder: (context, snapshot) {
          if (!snapshot.hasData) return const Center(child: CircularProgressIndicator());

          final data = snapshot.data!.data() as Map<String, dynamic>? ?? {};
          final currentCrop = CropModel.fromMap(data, widget.crop.id!);
          final netProfit = currentCrop.totalRevenue - currentCrop.totalExpenses;
          final isProfitable = netProfit >= 0;

          return SingleChildScrollView(
            padding: const EdgeInsets.all(16.0),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                // Οικονομική Κάρτα
                Card(
                  elevation: 3,
                  color: isProfitable ? Colors.green[50] : Colors.red[50],
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(12),
                    side: BorderSide(color: isProfitable ? Colors.green[300]! : Colors.red[300]!),
                  ),
                  child: Padding(
                    padding: const EdgeInsets.all(16.0),
                    child: Column(
                      children: [
                        Row(
                          mainAxisAlignment: MainAxisAlignment.spaceAround,
                          children: [
                            Column(
                              children: [
                                const Text('Έσοδα', style: TextStyle(color: Colors.green, fontWeight: FontWeight.bold)),
                                const SizedBox(height: 4),
                                Text('${currentCrop.totalRevenue.toStringAsFixed(2)} €',
                                    style: const TextStyle(fontSize: 18, fontWeight: FontWeight.bold, color: Colors.green)),
                              ],
                            ),
                            Container(height: 30, width: 1, color: Colors.grey[400]),
                            Column(
                              children: [
                                const Text('Έξοδα', style: TextStyle(color: Colors.red, fontWeight: FontWeight.bold)),
                                const SizedBox(height: 4),
                                Text('${currentCrop.totalExpenses.toStringAsFixed(2)} €',
                                    style: const TextStyle(fontSize: 18, fontWeight: FontWeight.bold, color: Colors.red)),
                              ],
                            ),
                          ],
                        ),
                        const Divider(height: 24),
                        Row(
                          mainAxisAlignment: MainAxisAlignment.center,
                          children: [
                            Text(
                              isProfitable ? 'Καθαρό Κέρδος: ' : 'Ζημιά: ',
                              style: TextStyle(fontSize: 16, fontWeight: FontWeight.bold, color: isProfitable ? Colors.green[900] : Colors.red[900]),
                            ),
                            Text(
                              '${netProfit.abs().toStringAsFixed(2)} €',
                              style: TextStyle(fontSize: 22, fontWeight: FontWeight.bold, color: isProfitable ? Colors.green[900] : Colors.red[900]),
                            ),
                          ],
                        ),
                      ],
                    ),
                  ),
                ),

                const SizedBox(height: 16),

                // Κουμπιά Προσθήκης Οικονομικών
                Row(
                  children: [
                    Expanded(
                      child: ElevatedButton.icon(
                        onPressed: _showAddExpenseDialog,
                        icon: const Icon(Icons.remove_circle_outline),
                        label: const Text('Έξοδο'),
                        style: ElevatedButton.styleFrom(backgroundColor: Colors.red[700], foregroundColor: Colors.white),
                      ),
                    ),
                    const SizedBox(width: 12),
                    Expanded(
                      child: ElevatedButton.icon(
                        onPressed: _showAddRevenueDialog,
                        icon: const Icon(Icons.add_circle_outline),
                        label: const Text('Έσοδο'),
                        style: ElevatedButton.styleFrom(backgroundColor: Colors.green[800], foregroundColor: Colors.white),
                      ),
                    ),
                  ],
                ),

                const SizedBox(height: 24),

                // Ενότητα Εργασιών (Task Planner)
                Row(
                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    const Text(
                      'Εργασίες & Υπομνήσεις',
                      style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold),
                    ),
                    ElevatedButton.icon(
                      onPressed: _showAddTaskDialog,
                      icon: const Icon(Icons.add, size: 18),
                      label: const Text('Νέα Εργασία'),
                      style: ElevatedButton.styleFrom(
                        backgroundColor: Colors.green[800],
                        foregroundColor: Colors.white,
                      ),
                    ),
                  ],
                ),
                const SizedBox(height: 8),

                StreamBuilder<QuerySnapshot>(
                  stream: FirebaseFirestore.instance
                      .collection('crops')
                      .doc(widget.crop.id)
                      .collection('tasks')
                      .snapshots(),
                  builder: (context, taskSnapshot) {
                    if (!taskSnapshot.hasData) {
                      return const Center(child: CircularProgressIndicator());
                    }

                    final taskDocs = taskSnapshot.data!.docs;

                    if (taskDocs.isEmpty) {
                      return const Padding(
                        padding: EdgeInsets.symmetric(vertical: 16.0),
                        child: Center(
                          child: Text('Δεν υπάρχουν καταγεγραμμένες εργασίες γι\' αυτή την καλλιέργεια.'),
                        ),
                      );
                    }

                    return ListView.builder(
                      shrinkWrap: true,
                      physics: const NeverScrollableScrollPhysics(),
                      itemCount: taskDocs.length,
                      itemBuilder: (context, index) {
                        final taskData = taskDocs[index].data() as Map<String, dynamic>;
                        final taskId = taskDocs[index].id;
                        final taskTitle = taskData['title'] ?? '';
                        final isCompleted = taskData['isCompleted'] ?? false;

                        return Card(
                          margin: const EdgeInsets.symmetric(vertical: 4),
                          child: CheckboxListTile(
                            title: Text(
                              taskTitle,
                              style: TextStyle(
                                decoration: isCompleted ? TextDecoration.lineThrough : null,
                                color: isCompleted ? Colors.grey : Colors.black,
                                fontWeight: FontWeight.w600,
                              ),
                            ),
                            value: isCompleted,
                            activeColor: Colors.green[800],
                            onChanged: (val) async {
                              await _firestoreService.toggleTaskStatus(
                                cropId: widget.crop.id!,
                                taskId: taskId,
                                currentStatus: isCompleted,
                              );
                            },
                          ),
                        );
                      },
                    );
                  },
                ),

                const SizedBox(height: 24),

                // Διακόπτης Δημοσίευσης στην Αγορά
                SwitchListTile(
                  title: const Text('Δημοσίευση στην Αγορά', style: TextStyle(fontWeight: FontWeight.bold)),
                  subtitle: const Text('Επιτρέψτε σε αγοραστές να βλέπουν τη σοδειά σας'),
                  value: _isPublished,
                  activeColor: Colors.green[800],
                  onChanged: (val) async {
                    setState(() => _isPublished = val);
                    await _firestoreService.togglePublishCrop(widget.crop.id!, val);
                  },
                ),
              ],
            ),
          );
        },
      ),
    );
  }
}
