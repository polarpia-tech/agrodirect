import 'package:flutter/material.dart';
import 'package:cloud_firestore/cloud_firestore.dart';
import '../models/crop_model.dart';
import '../services/firestore_service.dart';
import 'add_expense_screen.dart';

class CropDetailsScreen extends StatefulWidget {
  final CropModel crop;

  const CropDetailsScreen({Key? key, required this.crop}) : super(key: key);

  @override
  State<CropDetailsScreen> createState() => _CropDetailsScreenState();
}

class _CropDetailsScreenState extends State<CropDetailsScreen> {
  final FirestoreService _firestoreService = FirestoreService();
  late bool _isPublished;

  @override
  void initState() {
    super.initState();
    _isPublished = widget.crop.isPublished;
  }

  // Χρώματα ανά κατηγορία εξόδου
  Color _getCategoryColor(String category) {
    switch (category) {
      case 'Λιπάσματα':
        return Colors.green;
      case 'Καύσιμα':
        return Colors.orange;
      case 'Ημερομίσθια':
        return Colors.blue;
      case 'Φάρμακα':
        return Colors.purple;
      case 'Εξοπλισμός':
        return Colors.teal;
      case 'Γεωπόνος':
        return Colors.indigo;
      default:
        return Colors.grey;
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: Text(widget.crop.productName),
        backgroundColor: Colors.green[800],
        foregroundColor: Colors.white,
      ),
      body: StreamBuilder<QuerySnapshot>(
        stream: _firestoreService.getCropExpensesStream(widget.crop.id),
        builder: (context, snapshot) {
          if (snapshot.connectionState == ConnectionState.waiting) {
            return const Center(child: CircularProgressIndicator());
          }

          final docs = snapshot.data?.docs ?? [];
          double totalExpenses = 0.0;
          Map<String, double> categoryTotals = {};

          for (var doc in docs) {
            final data = doc.data() as Map<String, dynamic>;
            final amount = (data['amount'] as num?)?.toDouble() ?? 0.0;
            final category = (data['category'] as String?) ?? 'Άλλο';

            totalExpenses += amount;
            categoryTotals[category] = (categoryTotals[category] ?? 0.0) + amount;
          }

          return SingleChildScrollView(
            padding: const EdgeInsets.all(16.0),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                // Κάρτα Βασικών Στοιχείων
                Card(
                  elevation: 2,
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(12),
                  ),
                  child: Padding(
                    padding: const EdgeInsets.all(16.0),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Row(
                          mainAxisAlignment: MainAxisAlignment.spaceBetween,
                          children: [
                            Text(
                              widget.crop.productName,
                              style: const TextStyle(
                                fontSize: 22,
                                fontWeight: FontWeight.bold,
                              ),
                            ),
                            Switch(
                              value: _isPublished,
                              activeColor: Colors.green[800],
                              onChanged: (value) async {
                                setState(() {
                                  _isPublished = value;
                                });
                                await _firestoreService.toggleCropPublishStatus(
                                  widget.crop.id,
                                  value,
                                );
                              },
                            ),
                          ],
                        ),
                        Text(
                          _isPublished ? 'Δημοσιευμένο στην Αγορά' : 'Ιδιωτικό (Τετράδιο)',
                          style: TextStyle(
                            color: _isPublished ? Colors.green[800] : Colors.grey[600],
                            fontWeight: FontWeight.w600,
                          ),
                        ),
                        const Divider(height: 24),
                        Row(
                          mainAxisAlignment: MainAxisAlignment.spaceBetween,
                          children: [
                            _buildInfoTile('Έκταση', '${widget.crop.areaInAcre} στρ.'),
                            _buildInfoTile('Εκτίμηση', '${widget.crop.estimatedQuantityTons} τόν.'),
                            _buildInfoTile('Συνολικό Κόστος', '${totalExpenses.toStringAsFixed(2)} €'),
                          ],
                        ),
                      ],
                    ),
                  ),
                ),
                const SizedBox(height: 20),

                // Αναλυτική Οπτικοποίηση Εξόδων (Visual Breakdown)
                if (categoryTotals.isNotEmpty) ...[
                  const Text(
                    'Αναλυμός Εξόδων ανά Κατηγορία',
                    style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold),
                  ),
                  const SizedBox(height: 12),
                  Card(
                    elevation: 2,
                    shape: RoundedRectangleBorder(
                      borderRadius: BorderRadius.circular(12),
                    ),
                    child: Padding(
                      padding: const EdgeInsets.all(16.0),
                      child: Column(
                        children: categoryTotals.entries.map((entry) {
                          final category = entry.key;
                          final amount = entry.value;
                          final percentage = totalExpenses > 0 ? (amount / totalExpenses) : 0.0;
                          final color = _getCategoryColor(category);

                          return Padding(
                            padding: const EdgeInsets.symmetric(vertical: 8.0),
                            child: Column(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                                Row(
                                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                                  children: [
                                    Text(
                                      category,
                                      style: const TextStyle(fontWeight: FontWeight.bold),
                                    ),
                                    Text(
                                      '${amount.toStringAsFixed(2)} € (${(percentage * 100).toStringAsFixed(1)}%)',
                                      style: TextStyle(color: Colors.grey[700]),
                                    ),
                                  ],
                                ),
                                const SizedBox(height: 6),
                                ClipRRect(
                                  borderRadius: BorderRadius.circular(4),
                                  child: LinearProgressIndicator(
                                    value: percentage,
                                    minHeight: 8,
                                    backgroundColor: Colors.grey[200],
                                    valueColor: AlwaysStoppedAnimation<Color>(color),
                                  ),
                                ),
                              ],
                            ),
                          );
                        }).toList(),
                      ),
                    ),
                  ),
                  const SizedBox(height: 20),
                ],

                // Λίστα Καταγεγραμμένων Εξόδων
                Row(
                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    const Text(
                      'Ιστορικό Εξόδων',
                      style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold),
                    ),
                    ElevatedButton.icon(
                      onPressed: () {
                        Navigator.of(context).push(
                          MaterialPageRoute(
                            builder: (context) => AddExpenseScreen(cropId: widget.crop.id),
                          ),
                        );
                      },
                      icon: const Icon(Icons.add, size: 18),
                      label: const Text('Νέο Έξοδο'),
                      style: ElevatedButton.styleFrom(
                        backgroundColor: Colors.green[800],
                        foregroundColor: Colors.white,
                      ),
                    ),
                  ],
                ),
                const SizedBox(height: 8),

                if (docs.isEmpty)
                  const Padding(
                    padding: EdgeInsets.symmetric(vertical: 24.0),
                    child: Center(
                      child: Text('Δεν έχουν καταγραφεί έξοδα για αυτή την καλλιέργεια.'),
                    ),
                  )
                else
                  ListView.builder(
                    shrinkWrap: true,
                    physics: const NeverScrollableScrollPhysics(),
                    itemCount: docs.length,
                    itemBuilder: (context, index) {
                      final data = docs[index].data() as Map<String, dynamic>;
                      final title = data['title'] ?? 'Έξοδο';
                      final amount = (data['amount'] as num?)?.toDouble() ?? 0.0;
                      final category = data['category'] ?? 'Άλλο';

                      return Card(
                        margin: const EdgeInsets.symmetric(vertical: 4),
                        child: ListTile(
                          leading: CircleAvatar(
                            backgroundColor: _getCategoryColor(category).withOpacity(0.2),
                            child: Icon(
                              Icons.receipt_long,
                              color: _getCategoryColor(category),
                            ),
                          ),
                          title: Text(title, style: const TextStyle(fontWeight: FontWeight.w600)),
                          subtitle: Text('Κατηγορία: $category'),
                          trailing: Text(
                            '-${amount.toStringAsFixed(2)} €',
                            style: const TextStyle(
                              color: Colors.red,
                              fontWeight: FontWeight.bold,
                              fontSize: 15,
                            ),
                          ),
                        ),
                      );
                    },
                  ),
              ],
            ),
          );
        },
      ),
    );
  }

  Widget _buildInfoTile(String title, String value) {
    return Column(
      children: [
        Text(title, style: TextStyle(color: Colors.grey[600], fontSize: 12)),
        const SizedBox(height: 4),
        Text(value, style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 16)),
      ],
    );
  }
}
