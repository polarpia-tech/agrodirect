import 'package:flutter/material.dart';
import 'package:firebase_auth/firebase_auth.dart';
import '../models/crop_model.dart';
import '../services/firestore_service.dart';

class AddCropScreen extends StatefulWidget {
  const AddCropScreen({Key? key}) : super(key: key);

  @override
  State<AddCropScreen> createState() => _AddCropScreenState();
}

class _AddCropScreenState extends State<AddCropScreen> {
  final _formKey = GlobalKey<FormState>();
  final _productNameController = TextEditingController();
  final _areaController = TextEditingController();
  final _quantityController = TextEditingController();
  
  final FirestoreService _firestoreService = FirestoreService();
  bool _isLoading = false;

  @override
  void dispose() {
    _productNameController.dispose();
    _areaController.dispose();
    _quantityController.dispose();
    super.dispose();
  }

  Future<void> _saveCrop() async {
    if (_formKey.currentState!.validate()) {
      final user = FirebaseAuth.instance.currentUser;
      if (user == null) return;

      setState(() {
        _isLoading = true;
      });

      try {
        final newCrop = CropModel(
          userId: user.uid,
          productName: _productNameController.text.trim(),
          areaInAcre: double.parse(_areaController.text.trim()),
          estimatedQuantityTons: double.parse(_quantityController.text.trim()),
          isPublished: false,
          totalExpenses: 0.0,
          totalRevenue: 0.0,
          createdAt: DateTime.now(),
        );

        await _firestoreService.addCrop(newCrop);

        if (mounted) {
          Navigator.of(context).pop();
        }
      } catch (e) {
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text('Σφάλμα αποθήκευσης: $e')),
          );
        }
      } finally {
        if (mounted) {
          setState(() {
            _isLoading = false;
          });
        }
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text('Νέα Καλλιέργεια'),
        backgroundColor: Colors.green[800],
        foregroundColor: Colors.white,
      ),
      body: Padding(
        padding: const EdgeInsets.all(16.0),
        child: Form(
          key: _formKey,
          child: ListView(
            children: [
              TextFormField(
                controller: _productNameController,
                decoration: const InputDecoration(
                  labelText: 'Όνομα Προϊόντος (π.χ. Ελιές, Σιτάρι)',
                  prefixIcon: Icon(Icons.eco),
                ),
                validator: (value) {
                  if (value == null || value.trim().isEmpty) {
                    return 'Παρακαλώ εισάγετε όνομα προϊόντος';
                  }
                  return null;
                },
              ),
              const SizedBox(height: 16),
              TextFormField(
                controller: _areaController,
                keyboardType: const TextInputType.numberWithOptions(decimal: true),
                decoration: const InputDecoration(
                  labelText: 'Έκταση (σε Στρέμματα)',
                  prefixIcon: Icon(Icons.landscape),
                ),
                validator: (value) {
                  if (value == null || double.tryParse(value) == null) {
                    return 'Παρακαλώ εισάγετε έγκυρη έκταση';
                  }
                  return null;
                },
              ),
              const SizedBox(height: 16),
              TextFormField(
                controller: _quantityController,
                keyboardType: const TextInputType.numberWithOptions(decimal: true),
                decoration: const InputDecoration(
                  labelText: 'Εκτιμώμενη Παραγωγή (σε Τόνους)',
                  prefixIcon: Icon(Icons.fitness_center),
                ),
                validator: (value) {
                  if (value == null || double.tryParse(value) == null) {
                    return 'Παρακαλώ εισάγετε έγκυρη ποσότητα';
                  }
                  return null;
                },
              ),
              const SizedBox(height: 32),
              SizedBox(
                width: double.infinity,
                child: ElevatedButton(
                  onPressed: _isLoading ? null : _saveCrop,
                  style: ElevatedButton.styleFrom(
                    backgroundColor: Colors.green[800],
                    foregroundColor: Colors.white,
                    padding: const EdgeInsets.symmetric(vertical: 14),
                  ),
                  child: _isLoading
                      ? const CircularProgressIndicator(color: Colors.white)
                      : const Text(
                          'Αποθήκευση Καλλιέργειας',
                          style: TextStyle(fontSize: 16, fontWeight: FontWeight.bold),
                        ),
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}
