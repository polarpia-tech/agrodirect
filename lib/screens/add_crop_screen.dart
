import 'package:flutter/material.dart';
import '../models/crop_model.dart';

class AddCropScreen extends StatefulWidget {
  const AddCropScreen({Key? key}) : super(key: key);

  @override
  State<AddCropScreen> createState() => _AddCropScreenState();
}

class _AddCropScreenState extends State<AddCropScreen> {
  final _formKey = GlobalKey<FormState>();
  
  String _productName = '';
  double _areaInAcre = 0.0;
  double _estimatedQuantityTons = 0.0;
  String _notes = '';

  void _saveForm() {
    if (_formKey.currentState!.validate()) {
      _formKey.currentState!.save();
      
      // Δημιουργία νέου αντικειμένου καλλιέργειας
      final newCrop = CropModel(
        id: DateTime.now().toString(),
        farmerUid: 'farmer_101',
        productName: _productName,
        areaInAcre: _areaInAcre,
        estimatedHarvestDate: DateTime.now().add(const Duration(days: 30)),
        estimatedQuantityTons: _estimatedQuantityTons,
        status: 'growing',
        notes: _notes,
      );

      // Επιστροφή στην προηγούμενη οθόνη στέλνοντας τα νέα δεδομένα
      Navigator.of(context).pop(newCrop);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text('Νέα Καλλιέργεια'),
        backgroundColor: Colors.green[800],
      ),
      body: Padding(
        padding: const EdgeInsets.all(16.0),
        child: Form(
          key: _formKey,
          child: ListView(
            children: [
              TextFormField(
                decoration: const InputDecoration(
                  labelText: 'Όνομα Προϊόντος / Καλλιέργειας',
                  hintText: 'π.χ. Ντομάτες, Ελιές',
                  border: OutlineInputBorder(),
                ),
                validator: (value) {
                  if (value == null || value.isEmpty) {
                    return 'Παρακαλώ εισάγετε όνομα προϊόντος';
                  }
                  return null;
                },
                onSaved: (value) => _productName = value!,
              ),
              const SizedBox(height: 16),
              TextFormField(
                decoration: const InputDecoration(
                  labelText: 'Έκταση (Στρέμματα)',
                  border: OutlineInputBorder(),
                ),
                keyboardType: TextInputType.number,
                validator: (value) {
                  if (value == null || double.tryParse(value) == null) {
                    return 'Εισάγετε έναν έγκυρο αριθμό';
                  }
                  return null;
                },
                onSaved: (value) => _areaInAcre = double.parse(value!),
              ),
              const SizedBox(height: 16),
              TextFormField(
                decoration: const InputDecoration(
                  labelText: 'Εκτιμώμενη Παραγωγή (Τόνοι)',
                  border: OutlineInputBorder(),
                ),
                keyboardType: TextInputType.number,
                validator: (value) {
                  if (value == null || double.tryParse(value) == null) {
                    return 'Εισάγετε έναν έγκυρο αριθμό';
                  }
                  return null;
                },
                onSaved: (value) => _estimatedQuantityTons = double.parse(value!),
              ),
              const SizedBox(height: 16),
              TextFormField(
                decoration: const InputDecoration(
                  labelText: 'Σημειώσεις / Παρατηρήσεις',
                  border: OutlineInputBorder(),
                ),
                maxLines: 3,
                onSaved: (value) => _notes = value ?? '',
              ),
              const SizedBox(height: 24),
              ElevatedButton(
                onPressed: _saveForm,
                style: ElevatedButton.styleFrom(
                  backgroundColor: Colors.green[800],
                  foregroundColor: Colors.white,
                  padding: const EdgeInsets.symmetric(vertical: 14),
                ),
                child: const Text('Αποθήκευση Καλλιέργειας', style: TextStyle(fontSize: 16)),
              ),
            ],
          ),
        ),
      ),
    );
  }
}
