import 'package:flutter/material.dart';
import '../models/crop_model.dart';
import '../services/crop_service.dart';

class MarketplaceScreen extends StatefulWidget {
  const MarketplaceScreen({Key? key}) : super(key: key);

  @override
  State<MarketplaceScreen> createState() => _MarketplaceScreenState();
}

class _MarketplaceScreenState extends State<MarketplaceScreen> {
  final CropService _cropService = CropService();
  List<CropModel> _availableCrops = [];

  @override
  void initState() {
    super.initState();
    _availableCrops = _cropService.getMockCrops();
  }

  void _showContactDialog(CropModel crop) {
    showDialog(
      context: context,
      builder: (context) => AlertDialog(
        title: Text('Επικοινωνία για ${crop.productName}'),
        content: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text('Διαθέσιμη Ποσότητα: ${crop.estimatedQuantityTons} τόνοι'),
            const SizedBox(height: 8),
            Text('Αναμενόμενη Συγκομιδή: ${crop.estimatedHarvestDate.day}/${crop.estimatedHarvestDate.month}/${crop.estimatedHarvestDate.year}'),
            const SizedBox(height: 16),
            const Text(
              'Θέλετε να στείλετε αίτημα ενδιαφέροντος στον παραγωγό;',
              style: TextStyle(fontWeight: FontWeight.bold),
            ),
          ],
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(context).pop(),
            child: const Text('Ακύρωση'),
          ),
          ElevatedButton(
            onPressed: () {
              Navigator.of(context).pop();
              ScaffoldMessenger.of(context).showSnackBar(
                const SnackBar(
                  content: Text('Το αίτημα ενδιαφέροντος στάλθηκε επιτυχώς!'),
                  backgroundColor: Colors.green,
                ),
              );
            },
            style: ElevatedButton.styleFrom(
              backgroundColor: Colors.green[800],
              foregroundColor: Colors.white,
            ),
            child: const Text('Αποστολή Αιτήματος'),
          ),
        ],
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text('Αγορά & Διαθέσιμες Σοδειές'),
        backgroundColor: Colors.green[800],
      ),
      body: _availableCrops.isEmpty
          ? const Center(
              child: Text('Δεν υπάρχουν διαθέσιμες σοδειές στην αγορά.'),
            )
          : ListView.builder(
              itemCount: _availableCrops.length,
              itemBuilder: (context, index) {
                final crop = _availableCrops[index];
                return Card(
                  margin: const EdgeInsets.symmetric(
                      horizontal: 12, vertical: 6),
                  child: Padding(
                    padding: const EdgeInsets.all(12.0),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Row(
                          mainAxisAlignment: MainAxisAlignment.spaceBetween,
                          children: [
                            Text(
                              crop.productName,
                              style: const TextStyle(
                                fontSize: 18,
                                fontWeight: FontWeight.bold,
                              ),
                            ),
                            Container(
                              padding: const EdgeInsets.symmetric(
                                  horizontal: 8, vertical: 4),
                              decoration: BoxDecoration(
                                color: Colors.green[100],
                                borderRadius: BorderRadius.circular(8),
                              ),
                              child: Text(
                                'Διαθέσιμο',
                                style: TextStyle(
                                  color: Colors.green[800],
                                  fontWeight: FontWeight.bold,
                                  fontSize: 12,
                                ),
                              ),
                            ),
                          ],
                        ),
                        const SizedBox(height: 8),
                        Text(
                          'Εκτιμώμενη Παραγωγή: ${crop.estimatedQuantityTons} τόνοι',
                          style: const TextStyle(fontSize: 14),
                        ),
                        Text(
                          'Αναμενόμενη Συγκομιδή: ${crop.estimatedHarvestDate.day}/${crop.estimatedHarvestDate.month}/${crop.estimatedHarvestDate.year}',
                          style: const TextStyle(
                              fontSize: 14, color: Colors.grey),
                        ),
                        const SizedBox(height: 12),
                        SizedBox(
                          width: double.infinity,
                          child: OutlinedButton.icon(
                            onPressed: () => _showContactDialog(crop),
                            icon: const Icon(Icons.storefront),
                            label: const Text('Εκδήλωση Ενδιαφέροντος'),
                            style: OutlinedButton.styleFrom(
                              foregroundColor: Colors.green[800],
                              side: BorderSide(color: Colors.green[800]!),
                            ),
                          ),
                        ),
                      ],
                    ),
                  ),
                );
              },
            ),
    );
  }
}
